CREATE DATABASE IF NOT EXISTS undangan_digital CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE undangan_digital;

SET FOREIGN_KEY_CHECKS = 0;
DROP TABLE IF EXISTS ucapan, rsvp, tamu, galeri, cerita, rekening, acara, users;
SET FOREIGN_KEY_CHECKS = 1;

CREATE TABLE users (
  id INT AUTO_INCREMENT PRIMARY KEY,
  nama VARCHAR(100) NOT NULL,
  username VARCHAR(50) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL
) ENGINE=InnoDB;

-- Satu baris = satu undangan (bisa banyak pasangan / klien dalam satu aplikasi)
CREATE TABLE acara (
  id INT AUTO_INCREMENT PRIMARY KEY,
  slug VARCHAR(60) NOT NULL UNIQUE,
  pria_panggilan VARCHAR(40) NOT NULL,
  pria_nama VARCHAR(120) NOT NULL,
  pria_ortu VARCHAR(200),
  pria_foto VARCHAR(120),
  wanita_panggilan VARCHAR(40) NOT NULL,
  wanita_nama VARCHAR(120) NOT NULL,
  wanita_ortu VARCHAR(200),
  wanita_foto VARCHAR(120),
  urutan ENUM('wanita','pria') NOT NULL DEFAULT 'wanita',   -- nama siapa yang ditulis lebih dulu
  akad_waktu DATETIME NOT NULL,
  akad_selesai TIME NULL,
  akad_tempat VARCHAR(150) NOT NULL,
  akad_alamat VARCHAR(255),
  resepsi_waktu DATETIME NULL,
  resepsi_selesai TIME NULL,
  resepsi_tempat VARCHAR(150),
  resepsi_alamat VARCHAR(255),
  maps_url VARCHAR(500),
  kutipan TEXT,
  kutipan_sumber VARCHAR(100),
  palet VARCHAR(20) NOT NULL DEFAULT 'sage',
  musik VARCHAR(120),
  alamat_kado VARCHAR(255),
  maks_orang_default TINYINT NOT NULL DEFAULT 2,
  template_wa TEXT,                                   -- pesan WhatsApp ke tamu, boleh memakai {nama} {link} {pasangan} {tanggal}
  aktif TINYINT(1) NOT NULL DEFAULT 1,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE rekening (
  id INT AUTO_INCREMENT PRIMARY KEY,
  acara_id INT NOT NULL,
  bank VARCHAR(40) NOT NULL,
  nomor VARCHAR(40) NOT NULL,
  atas_nama VARCHAR(100) NOT NULL,
  FOREIGN KEY (acara_id) REFERENCES acara(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE cerita (
  id INT AUTO_INCREMENT PRIMARY KEY,
  acara_id INT NOT NULL,
  judul VARCHAR(80) NOT NULL,
  waktu VARCHAR(40) NOT NULL,
  isi TEXT NOT NULL,
  urut TINYINT NOT NULL DEFAULT 0,
  FOREIGN KEY (acara_id) REFERENCES acara(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE galeri (
  id INT AUTO_INCREMENT PRIMARY KEY,
  acara_id INT NOT NULL,
  file VARCHAR(120) NOT NULL,
  urut SMALLINT NOT NULL DEFAULT 0,
  FOREIGN KEY (acara_id) REFERENCES acara(id) ON DELETE CASCADE
) ENGINE=InnoDB;

-- Setiap tamu punya kode unik untuk link personal (…/?u=slug&k=KODE)
CREATE TABLE tamu (
  id INT AUTO_INCREMENT PRIMARY KEY,
  acara_id INT NOT NULL,
  kode CHAR(6) NOT NULL UNIQUE,
  nama VARCHAR(120) NOT NULL,
  wa VARCHAR(20),
  grup VARCHAR(40),
  maks_orang TINYINT NOT NULL DEFAULT 2,
  dibuka_at DATETIME NULL,
  dibuka_kali INT NOT NULL DEFAULT 0,
  dikirim_at DATETIME NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX (acara_id),
  FOREIGN KEY (acara_id) REFERENCES acara(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE rsvp (
  id INT AUTO_INCREMENT PRIMARY KEY,
  tamu_id INT NOT NULL UNIQUE,
  kehadiran ENUM('hadir','tidak','ragu') NOT NULL,
  jumlah TINYINT NOT NULL DEFAULT 1,
  updated_at DATETIME NOT NULL,
  FOREIGN KEY (tamu_id) REFERENCES tamu(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE ucapan (
  id INT AUTO_INCREMENT PRIMARY KEY,
  acara_id INT NOT NULL,
  tamu_id INT NULL,
  nama VARCHAR(120) NOT NULL,
  isi TEXT NOT NULL,
  kehadiran ENUM('hadir','tidak','ragu') NULL,
  tampil TINYINT(1) NOT NULL DEFAULT 1,
  ip VARCHAR(45),
  created_at DATETIME NOT NULL,
  INDEX (acara_id, id),
  FOREIGN KEY (acara_id) REFERENCES acara(id) ON DELETE CASCADE
) ENGINE=InnoDB;

